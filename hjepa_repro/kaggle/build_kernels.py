"""Write the Kaggle kernel folders (kernel_<name>/run.py + kernel-metadata.json) from kernel_body.py."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BODY = open(os.path.join(HERE, "kernel_body.py")).read()
OWNER = "seungwonryoo"
GEN_SLUG = "hjepa-ant-gen"
REPRO_SOURCES = []  # set to ["hjepa-ant-repro42"] when re-pushing to resume


def build(name, consts, kernel_sources):
    d = os.path.join(HERE, f"kernel_{name}")
    os.makedirs(d, exist_ok=True)
    head = "# GENERATED by build_kernels.py from kernel_body.py\n" + "".join(f"{k} = {v!r}\n" for k, v in consts.items())
    open(os.path.join(d, "run.py"), "w").write(head + BODY)
    slug = f"hjepa-ant-{name.replace('_', '-')}"
    json.dump({"id": f"{OWNER}/{slug}", "title": slug.replace("-", " ").title().replace("Hjepa", "HJEPA"), "code_file": "run.py",
               "language": "python", "kernel_type": "script", "is_private": True, "enable_gpu": True, "enable_internet": True,
               "dataset_sources": [], "competition_sources": [], "model_sources": [],
               "kernel_sources": [f"{OWNER}/{s}" for s in kernel_sources]},
              open(os.path.join(d, "kernel-metadata.json"), "w"), indent=2)
    return slug


def repro_job(model, planner, seed):
    return {"name": f"repro_{model}_seed{seed}", "model": model, "ckpt_seed": seed, "seed": seed, "config": f"ant_{planner}",
            "out": f"eval_{planner}", "n_tasks": 50, "overrides": []}


def sweep_job(h, seed, split, n_tasks, level="level3", model="hjepa_l3", config="ant_l3"):
    return {"name": f"sweep_{model}_h{h}_s{seed}", "model": model, "ckpt_seed": 42, "seed": seed, "config": config,
            "out": f"sweep/h{h}_s{seed}", "n_tasks": n_tasks, "horizon": h, "split": split,
            "overrides": [f"hierarchical_plan_config.{level}.horizon={h}", "load_eval_trajs_path=assets/eval_trajs/ant/expert_grid_d3_n50.pt",
                          f"eval.num_eval={n_tasks}"]}


if __name__ == "__main__":
    which = sys.argv[1]
    if which == "gen":
        print(build("gen", {"ROLE": "gen", "CKPT_INCLUDE": "ant/ant_lewm/seed42/*"}, []))
    elif which == "repro42":
        jobs = [repro_job("hjepa_l3", "l3", 42), repro_job("lewm", "flat", 42), repro_job("hjepa_l4", "l4", 42), repro_job("hwm_l3", "l3", 42)]
        print(build("repro42", {"ROLE": "jobs", "CKPT_INCLUDE": "ant/*", "JOBS": jobs, "N_WORKERS": 4, "TIER_STEP": 0, "WALL_LIMIT_S": 11 * 3600,
                                "TASK_FILE_NAME": ""}, REPRO_SOURCES))
    elif which in ("sweep1", "sweep2"):
        # PREREG.md: session 1 = split A seeds, session 2 = split B seeds; seed outer, horizon inner
        seeds, split = ((100, 101, 102), "A") if which == "sweep1" else ((103, 104, 105), "B")
        jobs = [sweep_job(h, s, split, 50) for s in seeds for h in (5, 3, 7)]
        limit_h = float(sys.argv[2])
        sources = sys.argv[3:]  # own slug when re-pushing to resume
        print(build(which, {"ROLE": "jobs", "CKPT_INCLUDE": "ant/ant_hjepa_l3/seed42/*", "JOBS": jobs, "N_WORKERS": 4, "TIER_STEP": 5,
                            "WALL_LIMIT_S": int(limit_h * 3600), "TASK_FILE_NAME": ""}, sources))
